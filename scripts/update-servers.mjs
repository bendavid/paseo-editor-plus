// Pins the language servers Editor Plus can install from GitHub releases: for each server and
// platform, the asset URL, size, and SHA-256 that GitHub records for it. Writes
// shared/server-releases.ts. Run after changing a tag below:
//   node scripts/update-servers.mjs
// Needs the GitHub CLI (`gh`), logged in. The npm and Go servers are pinned in shared/servers.ts.

import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";

const RELEASES = {
  tinymist: {
    repo: "Myriad-Dreamin/tinymist",
    tag: "v0.15.10",
    assets: {
      "linux-x64": "tinymist-x86_64-unknown-linux-gnu.tar.gz",
      "linux-arm64": "tinymist-aarch64-unknown-linux-gnu.tar.gz",
      "darwin-x64": "tinymist-x86_64-apple-darwin.tar.gz",
      "darwin-arm64": "tinymist-aarch64-apple-darwin.tar.gz",
      "win32-x64": "tinymist-x86_64-pc-windows-msvc.zip",
      "win32-arm64": "tinymist-aarch64-pc-windows-msvc.zip",
    },
  },
  "rust-analyzer": {
    repo: "rust-lang/rust-analyzer",
    tag: "2026-10-19",
    assets: {
      "linux-x64": "rust-analyzer-x86_64-unknown-linux-gnu.gz",
      "linux-arm64": "rust-analyzer-aarch64-unknown-linux-gnu.gz",
      "darwin-x64": "rust-analyzer-x86_64-apple-darwin.gz",
      "darwin-arm64": "rust-analyzer-aarch64-apple-darwin.gz",
      "win32-x64": "rust-analyzer-x86_64-pc-windows-msvc.zip",
      "win32-arm64": "rust-analyzer-aarch64-pc-windows-msvc.zip",
    },
  },
  clangd: {
    repo: "clangd/clangd",
    tag: "23.1.0",
    // The macOS build runs on Apple silicon through Rosetta; there is no Linux arm64 build.
    assets: {
      "linux-x64": "clangd-linux-23.1.0.zip",
      "darwin-x64": "clangd-mac-23.1.0.zip",
      "darwin-arm64": "clangd-mac-23.1.0.zip",
      "win32-x64": "clangd-windows-23.1.0.zip",
    },
  },
  texlab: {
    repo: "latex-lsp/texlab",
    tag: "v5.26.0",
    assets: {
      "linux-x64": "texlab-x86_64-linux.tar.gz",
      "linux-arm64": "texlab-aarch64-linux.tar.gz",
      "darwin-x64": "texlab-x86_64-macos.tar.gz",
      "darwin-arm64": "texlab-aarch64-macos.tar.gz",
      "win32-x64": "texlab-x86_64-windows.zip",
      "win32-arm64": "texlab-aarch64-windows.zip",
    },
  },
  marksman: {
    repo: "artempyanykh/marksman",
    tag: "2026-02-08",
    assets: {
      "linux-x64": "marksman-linux-x64",
      "linux-arm64": "marksman-linux-arm64",
      "darwin-x64": "marksman-macos",
      "darwin-arm64": "marksman-macos",
      "win32-x64": "marksman.exe",
    },
  },
};

const out = {};
for (const [id, { repo, tag, assets }] of Object.entries(RELEASES)) {
  const release = JSON.parse(
    execFileSync("gh", ["api", `repos/${repo}/releases/tags/${tag}`], { encoding: "utf8" }),
  );
  const byName = new Map(release.assets.map((asset) => [asset.name, asset]));
  const platforms = {};
  for (const [platform, name] of Object.entries(assets)) {
    const asset = byName.get(name);
    if (!asset) throw new Error(`${repo} ${tag} has no asset ${name}`);
    if (!asset.digest?.startsWith("sha256:")) throw new Error(`${name} has no SHA-256 digest`);
    platforms[platform] = {
      url: asset.browser_download_url,
      size: asset.size,
      sha256: asset.digest.slice("sha256:".length),
    };
  }
  out[id] = { version: tag.replace(/^v/, ""), repo, platforms };
}

const body = `// Generated by scripts/update-servers.mjs. Do not edit; change the tags there and run it.

import type { ReleaseServers } from "./servers";

export const RELEASES: ReleaseServers = ${JSON.stringify(out, null, 2)};
`;
writeFileSync(new URL("../shared/server-releases.ts", import.meta.url), body);
console.log(
  Object.entries(out)
    .map(([id, r]) => `${id} ${r.version}: ${Object.keys(r.platforms).join(", ")}`)
    .join("\n"),
);
